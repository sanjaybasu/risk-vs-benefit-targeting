"""Write DATA.md from data/raw/*/FETCH.json and results/dataset_table.json."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOT_LOADED = {
    "crash2": "public file (hbiostat.org) has no treatment allocation column; not usable as an RCT",
    "upworthy": "aggregated clicks per headline arm; no viewer covariates; fits `choose`, not targeting",
    "llmrouterbench": "JSON per model per benchmark; layout check pending",
    "lmarena": "pairwise human preferences only; cannot give every model's outcome per prompt",
}


def main() -> None:
    table = json.loads((ROOT / "results" / "dataset_table.json").read_text())
    lines = [
        "# DATA",
        "",
        "Every dataset is public. Raw files live in `data/raw/<dataset>/` (gitignored); "
        "`FETCH.json` in each folder records URL, fetch time, size, and SHA-256. "
        "Generated by `scripts/04_dataset_table.py`; do not edit by hand.",
        "",
        "## Loaded datasets",
        "",
        "| Dataset | Tier | Outcome (better) | Rows | Test rows | Treated share | Outcome mean (context+dev) "
        "| Reproduction | Detectable gap at q = 20% | License | Commercial use |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k, r in table.items():
        if "error" in r:
            lines.append(f"| {k} | | | | | | | ERROR: {r['error']} | | | |")
            continue
        rep = r["reproduction"]
        pub = "n/a" if rep["published"] is None else f"{rep['published']:g}"
        repro = f"{rep['reproduced']:.4g} vs {pub} ({rep['status']})"
        mde = f"{r['mde_in_outcome_sd']:.2f} SD"
        lines.append(
            f"| {k} | {r['tier']} | {r['outcome']} ({r['better']}) | {r['rows']:,} | {r['test']:,} | "
            f"{r['treated_share']:.3f} | {r['outcome_mean_context_dev']:.4g} | {repro} | {mde} | "
            f"{r['license']} | {'yes' if r['commercial_use'] else 'no'} |"
        )
    lines += ["", "## Downloaded but not loaded", ""]
    lines += [f"- **{k}**: {v}" for k, v in NOT_LOADED.items()]
    lines += ["", "## Provenance", "", "| Dataset | File | Bytes | SHA-256 | Source |", "|---|---|---|---|---|"]
    for f in sorted((ROOT / "data" / "raw").glob("*/FETCH.json")):
        for e in json.loads(f.read_text()):
            lines.append(
                f"| {e['dataset']} | {e['file']} | {e.get('bytes', '')} | "
                f"`{e.get('sha256', e.get('commit', ''))[:16]}` | {e['url']} |"
            )
    lines += [
        "",
        "## Terms that restrict use",
        "",
        "- Criteo uplift (CC BY-NC-SA 4.0) and the Oregon public-use files (NBER click-through: no "
        "commercial use, no re-identification, cite) are evaluation-only. No model that Waymark sells "
        "is trained on them.",
        "- Hillstrom, NSW, IHDP, RouterBench data, and SWE-bench experiments state no license; treat "
        "as research use only until counsel reads them.",
        "- Camden (CC0), Michigan social pressure (CC0), Illinois (CC0), and IST (ODC-By, attribution) "
        "permit commercial use.",
        "",
        "The detectable gap is the smallest difference, in outcome standard deviations, between two "
        "rankings' mean effect among the top 20% that the test split detects with 80% power at a "
        "two-sided 0.05 level. It treats the two selected sets as independent, so it is conservative.",
    ]
    (ROOT / "DATA.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
