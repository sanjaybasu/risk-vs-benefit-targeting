"""Re-derive CANONICAL_NUMBERS.md from results files, then list canonical values missing from the manuscript.

Usage: uv run python verify_canonical.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = ROOT / "results"
MS = ROOT.parents[1] / "notebooks" / "system-three" / "paper" / "risk_vs_benefit_targeting_forecast_causal_models_pnas_maintext.md"


def f2(x):
    return f"{x:.2f}"


def f1(x):
    return f"{x:.1f}"


def main() -> None:
    h = json.loads((R / "h1_analysis.json").read_text())
    ex = json.loads((R / "h1_exploratory_sensitivity.json").read_text())["without_gusto_synbiotic"]
    sm = json.loads((R / "scoring_summary.json").read_text())
    hf = json.loads((R / "holdout_forecasts.json").read_text())
    p = h["H1_primary"]
    rows = [
        ("H1 slope (95% CI), P", f"{f2(p['slope'])} ({f2(p['lo95'])} to {f2(p['hi95'])}), P = {p['p_two_sided']:.2f}"),
        ("H1 intercept", f2(p["intercept"])),
        ("Joint test intercept 0, slope 1", f"F = {f2(p['joint_0_1']['F'])}, P = {p['joint_0_1']['p']:.2f}"),
        ("Holdout LPD gain (nats); succeeds", f"{f2(h['holdout_lpd_gain_nats'])}; {h['holdout_forecast_succeeds']}"),
        ("LOTO LPD gain (nats)", f2(h["loo_lpd_gain_nats"])),
        ("H1b slope (95% CI)", f"{f2(h['H1b']['slope'])} ({f2(h['H1b']['lo95'])} to {f2(h['H1b']['hi95'])})"),
        ("Exploratory: H1 without GUSTO-I and synbiotic", f"{f2(ex['slope'])} ({f2(ex['lo95'])} to {f2(ex['hi95'])})"),
        ("H1 with sign-flip trials", f"{f2(h['H1_with_sign_flip_trials']['slope'])} "
         f"({f2(h['H1_with_sign_flip_trials']['lo95'])} to {f2(h['H1_with_sign_flip_trials']['hi95'])})"),
        ("Pooled benefit minus scale, per 1,000", f"{f1(sm['pooled_main_benefit-minus-scale_q20']['mean'])} "
         f"({f1(sm['pooled_main_benefit-minus-scale_q20']['lo95'])} to {f1(sm['pooled_main_benefit-minus-scale_q20']['hi95'])})"),
    ]
    for s, r in sm["pooled_benefit_minus_risk_q20"].items():
        rows.append((f"Pooled {s} benefit minus risk, per 1,000", f"{f1(r['mean'])} ({f1(r['lo95'])} to {f1(r['hi95'])})"))
    for t, r in hf["forecasts"].items():
        rows.append((f"Holdout {t}: H1 forecast, observed", f"{f1(r['h1']['mean'])}, "
                     f"{f1(sm['per_trial'][t]['predictions']['scale-minus-risk']['estimate'])}"))
    md = ["# Canonical numbers (generated by verify_canonical.py from results/; do not edit by hand)", "",
          "| Quantity | Value |", "|---|---|"] + [f"| {a} | {b} |" for a, b in rows]
    (ROOT / "CANONICAL_NUMBERS.md").write_text("\n".join(md) + "\n")
    text = MS.read_text() if MS.exists() else ""
    print("\n".join(md))
    miss = [a for a, b in rows if b.split(" ")[0].rstrip(",;") not in text]
    print("\nfirst value not found in manuscript:", miss or "none")


if __name__ == "__main__":
    main()
