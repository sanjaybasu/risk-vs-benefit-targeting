"""Re-derive CANONICAL_NUMBERS.md from results/final_results.json via the manuscript provenance registry.

Runs notebooks/system-three/paper/audit/verify_numbers.py (which re-derives every registered number from the
results files and checks that it appears verbatim in the manuscript), then writes its registry here.
Exit code is non-zero if any registered number is missing from the manuscript.
Usage: python3 verify_canonical.py
"""

from __future__ import annotations

import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
AUDIT = ROOT.parents[1] / "notebooks" / "system-three" / "paper" / "audit"


def main() -> None:
    rc = subprocess.run([sys.executable, str(AUDIT / "verify_numbers.py")]).returncode
    rows = list(csv.DictReader(open(AUDIT / "data_provenance.csv")))
    out = ["# Canonical numbers (generated by verify_canonical.py from results/final_results.json; do not edit by hand)\n",
           "| Claim | Value as reported | Source | In manuscript |", "|---|---|---|---|"]
    out += [f"| {r['claim_id']} | {r['reported_value']} | {r['source']} | {r['found_in_manuscript']} |" for r in rows]
    (ROOT / "CANONICAL_NUMBERS.md").write_text("\n".join(out) + "\n")
    sys.exit(rc)


if __name__ == "__main__":
    main()
